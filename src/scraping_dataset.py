import pandas as pd
from google_play_scraper import reviews, Sort
result, _ = reviews(
    'com.gojek.app',
    lang='id',
    country='id',
    sort=Sort.NEWEST,
    count=12000
)

df = pd.DataFrame(result)

df = df[['content', 'score']]

df.columns = ['review', 'rating']
df.to_csv('dataset.csv', index=False)
print("Jumlah data:", df.shape)
